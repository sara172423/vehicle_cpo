function export(results, cfg)
    % Export a compact research artifact set.
    %
    % Files written here:
    %   - summary_results.csv
    %   - raw_results.csv          (unless summaryOnly=true)
    %   - metadata.json
    %
    % Figure PNG/PDF files are written separately by bench.plots().
    % For Figure 6, bench.plots() also writes figure_6_nfe.png/.pdf.

    out = char(cfg.outputDir);
    if ~isfolder(out)
        mkdir(out);
    end

    % Remove artifacts produced by older versions so an existing results
    % folder does not keep obsolete files after a new run.
    removeLegacyArtifacts(out, cfg.summaryOnly);

    % Keep the two CSV files that are most useful for analysis/review.
    bench.writeCsv(fullfile(out, 'summary_results.csv'), results.summary);

    if ~cfg.summaryOnly
        bench.writeCsv(fullfile(out, 'raw_results.csv'), results.raw);
    end

    % For multi-fitness experiments, keep one compact final-result table with
    % comparable physical/paper metrics for every fitness/algorithm run.
    fitnessComparisonPath = fullfile(out, 'fitness_comparison_results.csv');
    if numel(cfg.fitnesses) > 1
        bench.writeCsv(fitnessComparisonPath, results.executionAudit);
    elseif isfile(fitnessComparisonPath)
        delete(fitnessComparisonPath);
    end

    % Keep reproducibility/scientific metadata in one JSON file instead of
    % exporting several auxiliary CSV/JSON files. Detailed audit/statistics
    % remain available inside this metadata structure.
    metadata = rmfield(results, {'raw', 'summary', 'applications', 'convergence', 'runs'});
    metadata.article_doi = '10.1109/TVT.2025.3540639';
    metadata.matlab_runtime_verified = false;
    metadata.reconstruction_assumptions = { ...
        'Stored DAG realizations are unpublished reconstructions'; ...
        sprintf('Source-program bits = roundEven(%.6g * service-environment bits), numeric source size unpublished', cfg.sourceProgramFraction); ...
        'Compile work is supplied by task-type snapshots, numeric Wk unpublished'; ...
        'V2V and sender-power model follow uploaded Python declared approximations'; ...
        'One static joint scheduling epoch; the article parameter of 10 applications/s is retained as provenance but not dynamically simulated because no arrival-process formulation is published'; ...
        'Remote MEC uses access RSU and zero added backhaul delay/energy'; ...
        'Cache Eq40 counts OTHER cached providers, preserving uploaded implementation'; ...
        'Wilcoxon auto policy follows SciPy 1.17; statisticsMode=none reproduces no-SciPy null p-values' ...
    };
    metadata.reconstruction_parameters = struct( ...
        'deadline_sampling_weights_30_to_100_ms', cfg.deadlineSamplingWeights, ...
        'source_program_fraction', cfg.sourceProgramFraction, ...
        'application_arrival_model', 'static_joint_epoch', ...
        'figure9_vehicle_process', 'per-lane_homogeneous_spatial_poisson', ...
        'rsu_association', 'max_instantaneous_v2i_channel_gain_within_cell');
    metadata.fitness_configuration = struct( ...
        'selected_fitnesses', {cfg.fitnesses}, ...
        'fitness_1', 'Exact article total offloading efficiency; immutable baseline', ...
        'fitness_load_aware', 'Load-aware weighted sum: (1-lambda)*PaperQ + lambda*N*Jain(MEC busy time)', ...
        'load_aware_weight', cfg.loadAwareWeight, ...
        'load_metric', 'MEC busy time -> Jain fairness -> load imbalance = 1-Jain', ...
        'cross_fitness_score_warning', 'Do not compare raw optimization_score magnitudes across different fitness definitions; compare paper_total_efficiency, delay, energy, load, completion rate and task-mode counts');

    if strcmp(cfg.figure, 'figure_11')
        metadata.figure_11_definition = struct( ...
            'status', 'Original research extension; not a figure from the source article', ...
            'x', 'Mission vehicle count, article Figure 7 scenarios', ...
            'y', 'Jain fairness of total MEC busy time across all MEC servers', ...
            'higher_is_better', true, ...
            'summary', 'Per-algorithm mean across independent seeds; +/- one SD when n>1', ...
            'zero_mec_load_warning', 'FitnessLibrary reports Jain=1 for zero MEC usage (0/0 convention); inspect mec_busy_time_total_s', ...
            'cross_fitness_warning', 'Draw separate Fitness 1 and Fitness 2 figures; compare only identical metric definitions and physical outcomes');
    end

    writeJson(fullfile(out, 'metadata.json'), metadata);
end

function removeLegacyArtifacts(out, summaryOnly)
    obsolete = { ...
        'application_results.csv', ...
        'convergence_results.csv', ...
        'execution_audit.csv', ...
        'experiment_result.json', ...
        'nfe_summary_results.csv', ...
        'pairwise_statistics.csv' ...
    };

    for i = 1:numel(obsolete)
        path = fullfile(out, obsolete{i});
        if isfile(path)
            delete(path);
        end
    end

    % If this run explicitly requests summary-only output, remove a raw CSV
    % left by an earlier non-summary run in the same folder.
    if summaryOnly
        path = fullfile(out, 'raw_results.csv');
        if isfile(path)
            delete(path);
        end
    end
end

function writeJson(path, x)
    fid = fopen(path, 'w');
    assert(fid >= 0, 'Could not open JSON output file: %s', path);
    cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
    fwrite(fid, jsonencode(x), 'char');
end
