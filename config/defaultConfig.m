function cfg = defaultConfig()
    % Main experiment settings. Override these fields in the Command Window.
    % Physics/DAG/resource values remain in data/dataset.json.
    root = fileparts(fileparts(mfilename('fullpath')));

    cfg = struct( ...
        'figure', 'figure_6', ...                  % figure_6 ... figure_10
        'algorithms', {{}}, ...                   % Empty = DCSGA/Cuckoo baseline
        'experimentMode', '', ...                 % Auto, paper_reproduction, fair_optimizer_comparison
        'repetitions', [], ...                    % Empty = figure-specific default
        'statisticsMode', 'scipy_1_17', ...       % or 'none'
        'seedStart', 1, ...                       % First repetition seed
        'deadlineSamplingWeights', [5 10 15 20 20 15 10 5], ...
        'sourceProgramFraction', 0.10, ...
        'fitnesses', {{'fitness_1'}}, ...          % {'fitness_1'} or {'fitness_load_aware'} or both
        'loadAwareWeight', 0.05, ...              % lambda_L for Load-Aware Weighted-Sum fitness
        'populationSize', 50, ...
        'tmax', 15, ...                           % Search-loop safety limit
        'maxFunctionEvaluations', [], ...         % Common NFE cap in fair mode
        'vehicleCount', 76, ...
        'diagnosticVehicleCount', [], ...
        'diagnosticRoadVehicleCount', [], ...
        'diagnosticSweepValues', [], ...
        'exportArtifacts', true, ...
        'summaryOnly', false, ...
        'outputDir', fullfile(root, 'results'), ...
        'dataDir', fullfile(root, 'data', 'dataset.json'));
end
